/**
  Helper filter function for quick searching and tab categorization
 */
export function filterInstitutions(
  searchQuery: string,
  categoryFilter: string = 'ALL'
): UniversityOption[] {
  const query = searchQuery.trim().toLowerCase();

  return UNIVERSITIES.filter((inst) => {
    // Category check
    let matchesCategory = true;
    if (categoryFilter === 'Federal Universities') {
      matchesCategory = inst.category === 'Federal University';
    } else if (categoryFilter === 'State Universities') {
      matchesCategory = inst.category === 'State University';
    } else if (categoryFilter === 'Private Universities') {
      matchesCategory = inst.category === 'Private University';
    } else if (categoryFilter === 'Polytechnics') {
      matchesCategory = !!inst.isPolytechnic || inst.category.includes('Polytechnic');
    } else if (categoryFilter === 'Colleges of Education') {
      matchesCategory = !!inst.isCollege || inst.category === 'College of Education';
    }

    if (!matchesCategory) return false;

    if (!query) return true;

    return (
      inst.name.toLowerCase().includes(query) ||
      inst.code.toLowerCase().includes(query) ||
      inst.city.toLowerCase().includes(query) ||
      inst.state.toLowerCase().includes(query)
    );
  });
}
